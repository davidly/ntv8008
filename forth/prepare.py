#!/usr/bin/env python3
"""Expand the small AS macro dialect used by Baker's Forth into A08 syntax.

This deliberately supports these pinned inputs, not arbitrary AS programs.
The generated assembly is built by the repository's existing A08 assembler.
"""
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'forth/upstream'
QUOTED = r'''(?:'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*")'''


def parts(line):
    # Semicolons within quoted dictionary names are data, not comments.
    tokens = re.findall(QUOTED + r'|;.*|[^;\'\"]+', line)
    return ''.join(t for t in tokens if not t.startswith(';')).strip()


def outside(text, function):
    return ''.join(t if re.fullmatch(QUOTED, t) else function(t)
                   for t in re.split('(' + QUOTED + ')', text) if t)


class Expander:
    def __init__(self):
        self.macros = {}
        self.serial = 0

    def expand(self, lines, local=False):
        lines = [parts(line) for line in lines]
        if local:
            self.serial += 1
            labels = re.findall(r'^([\w]+):', '\n'.join(lines), re.M)
            for label in labels:
                lines = [outside(line, lambda s: re.sub(
                    r'\b' + re.escape(label) + r'\b',
                    'LOCAL%d_%s' % (self.serial, label), s)) for line in lines]
        result = []
        i = 0
        while i < len(lines):
            line = lines[i]
            i += 1
            if not line:
                continue
            macro = re.fullmatch(r'(\w+):?\s+macro(?:\s+(.*))?', line, re.I)
            repeat = re.fullmatch(r'rept\s+(\d+)', line, re.I)
            if macro or repeat:
                depth, start = 1, i
                while depth:
                    if re.search(r'\b(macro|rept)\b', lines[i], re.I):
                        depth += 1
                    if lines[i].lower() == 'endm':
                        depth -= 1
                    i += 1
                body = lines[start:i-1]
                if macro:
                    self.macros[macro[1].lower()] = (
                        (macro[2] or '').replace(',', ' ').split(), body)
                else:
                    for _ in range(int(repeat[1])):
                        result += self.expand(body, True)
                continue
            label = re.match(r'^(\w+):\s*(.*)$', line)
            if label:
                if label[2].lower().startswith('equ '):
                    result.append(label[1] + ' ' + label[2])
                    continue
                result.append(label[1] + ':')
                line = label[2]
                if not line:
                    continue
            op, _, args = line.partition(' ')
            if op.lower() in self.macros:
                parameters, body = self.macros[op.lower()]
                values = [v.strip() for v in args.split(',')] if args else []
                # AS permits unused/missing arguments (codeword_DOCOL x).
                mapped = dict(zip(parameters, values))
                def substitute(s):
                    for key, value in mapped.items():
                        # AS also substitutes after an underscore (cw_x).
                        s = re.sub(r'(?<![A-Za-z0-9])' + re.escape(key) +
                                   r'(?![A-Za-z0-9])', lambda _: value, s)
                    return s
                result += self.expand([outside(s, substitute) for s in body], True)
            else:
                result.append(line)
        return result


def expression(s):
    def convert(s):
        s = s.replace('|', ' OR ')
        s = re.sub(r'\b(lo|hi)\(', lambda m: '(LOW ' if m[1].lower() == 'lo'
                   else '(HIGH ', s, flags=re.I)
        # A08 defaults to octal; AS source defaults to decimal.
        return re.sub(r'\b\d+\b', lambda m: m[0] + 'D', s)
    s = re.sub(QUOTED, lambda m: str(ord(ast.literal_eval(m[0])[0])), s)
    return outside(s, convert)


def translate(lines):
    aliases = dict(call='CAL', jnz='JFZ', jz='JTZ', jnc='JFC', jc='JTC',
                   jm='JTS', jp='JFS', rz='RTZ', rnz='RFZ', rc='RTC',
                   rnc='RFC', ana='ND', ora='OR', xra='XR', cmp='CP',
                   add='AD', adc='AC', sub='SU', sbb='SB', ani='NDI',
                   ori='ORI', xri='XRI', sui='SUI')
    out = ['; Generated by forth/prepare.py from Scott Baker 8008-Forth.',
           '; Upstream provenance and licensing: ../forth/NOTICE.txt',
           '        ORG 0040H', '        JMP rom_start']
    for line in lines:
        if line.endswith(':'):
            out.append(line)
            continue
        op, _, args = line.partition(' ')
        op = op.lower()
        args = args.strip()
        if op == 'mov':
            a, b = [x.strip() for x in args.split(',')]
            out.append('        L' + a.upper() + b.upper())
        elif op == 'mvi':
            reg, value = args.split(',', 1)
            out.append('        L' + reg.upper() + 'I ' + expression(value))
        elif op in ('inr', 'dcr'):
            out.append('        ' + ('IN' if op == 'inr' else 'DC') + args.upper())
        elif op in ('ana','ora','xra','cmp','add','adc','sub','sbb'):
            out.append('        ' + aliases[op] + args.upper())
        elif op == 'db':
            data = []
            for token in re.findall(QUOTED + r'|[^,]+', args):
                token = token.strip()
                if token[0:1] in ('"', "'"):
                    data += [str(b) + 'D' for b in ast.literal_eval(token).encode('ascii')]
                elif token:
                    data.append(expression(token))
            # Keep generated source below A08's line-size limit.
            for start in range(0, len(data), 8):
                out.append('        DB ' + ','.join(data[start:start+8]))
        elif re.match(r'^\w+\s+equ\s+', line, re.I):
            name, _, value = re.split(r'\s+', line, maxsplit=2)
            out.append(name + ' EQU ' + expression(value))
        else:
            out.append('        ' + aliases.get(op, op.upper()) +
                       (' ' + expression(args) if args else ''))
    out.append('        END')
    return '\n'.join(line if line.startswith(';') else
                     outside(line, str.upper) for line in out) + '\n'


def prepare():
    source = (UPSTREAM / 'forth.asm').read_text()
    source = source.replace("db 2,'C','G'", "db 2,'C','@'")
    source = source.replace('            include "bitfuncs.inc"', '')
    source = re.sub(r'^\s*(PAGE|cpu) .*$','', source, flags=re.M)
    start = source.index('                ifdef serscel')
    end = source.index('                org 2100H', start)
    source = source[:start] + source[end:]
    extra = (UPSTREAM / 'forth-extra.inc').read_text()
    extra = extra.replace("db 9|F_IMMED,'[','R','E','C','U','R','S','E',']'",
                          "db 7|F_IMMED,'R','E','C','U','R','S','E'")
    # Put VARIABLE storage after its dictionary header/body, so ALLOT can
    # extend it without overwriting the variable's own executable definition.
    start = extra.index('cw_VARIABLE:')
    end = extra.index('name_VALUE:', start)
    extra = extra[:start] + '''cw_VARIABLE: codeword_DOCOL
                cw WORD
                cw CREATE
                cw DOCOL
                cw COMMA
                cw TICK
                cw LIT
                cw COMMA
                cw HERE
                cw FETCH
                cw_lit 4
                cw ADD
                cw COMMA
                cw TICK
                cw EXIT
                cw COMMA
                cw_lit 0
                cw COMMA
                cw EXIT

''' + extra[end:]
    native = (ROOT / 'forth/native.inc').read_text()
    extra = extra.replace('LASTWORD_EXTRA:', native+'\nLASTWORD_EXTRA:')
    extra = extra.replace('name_SEE:       linklast CFAT',
                          'name_SEE:       linklast BITCLEAR')
    source = source.replace('include "forth-extra.inc"', extra)
    source = source.replace('include "bufio.inc"',
                            (UPSTREAM / 'bufio.inc').read_text())
    # Forth emits LF; map it to host CR and suppress embedded CR in CR/LF.
    source = re.sub(r'^_EMIT:.*?(?=\n\n)',
                    '_EMIT: JMP CPRINT', source, flags=re.S | re.M)
    serial = '''
SINIT: RET
CPRINT: CPI 0DH
        RTZ
        CPI 0AH
        JFZ CWRITE
        LAI 0DH
CWRITE: OUT 0AH
        RET
CINP:   INP 2
        NDA
        JFS CINP
        NDI 07FH
        CAL CPRINT
        RET
'''
    # Serial snippet is already in old syntax and inserted after translation.
    source = source.replace('include "lib/serial.inc"', '')
    source = source.replace('                org 2100H', '                org 2000H')
    source = re.sub(r'^(\w+)([ \t]+)(?!(?:equ|macro)\b)',
                    r'\1:\2', source, flags=re.I | re.M)
    result = translate(Expander().expand(source.splitlines()))
    return result.replace('        END\n', serial + '        END\n')


if __name__ == '__main__':
    (ROOT / 'a08/forth.asm').write_bytes(prepare().encode('ascii'))
