#!/usr/bin/env python3
"""Adapt the archived 2012 SCELBAL source for A08 and ntv8008, offline."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'scelbal/upstream/sc1fast.asm'
OUTPUT = ROOT / 'a08/scelbal.asm'

CONSOLE = '''; Character console for ntv8008; preserve C/D/E/H/L for STRIN and ECHO.
INPORT: EQU 2
OUTPORT: EQU 12
CINP:   INP INPORT
        NDI 177
        CPI 010                ; backspace or DEL becomes SCELBAL rubout
        JTZ RUBOUT
        CPI 177
        JTZ RUBOUT
        CPI 'a'
        JTC MARK
        CPI 'z'+1
        JFC MARK
        SUI 040                ; uppercase the input, including quoted strings
MARK:   ORI 200                ; SCELBAL uses mark-parity ASCII internally
        CPI 215
        RTZ                    ; STRIN emits the newline after Enter
        OUT OUTPORT            ; echo characters on the raw terminal
        RET
RUBOUT: LAI 377
        RET
UDEFX:  HLT                    ; no user-defined machine-code function installed
CPRINT: NDI 177
        CPI 015
        RTZ                    ; omit CR: LF is the host newline
        CPI 024
        RTZ                    ; omit the READY message's old terminal control
        OUT OUTPORT
        RET

'''


def adapt():
    source = UPSTREAM.read_text()
    # AS8 HIGH/LOW spelling and decimal counts in its DATA * reservation syntax.
    source = source.replace('\\HB\\', 'HIGH ').replace('\\LB\\', 'LOW ')
    source = re.sub(r'DATA \*(\d+)', lambda m: 'DS ' + m[1] + 'D', source)
    # AS8 quotes imply mark-parity ASCII. The SCR string lacks a closing quote
    # in the archive; its newline terminates the string in the original assembler.
    source = re.sub(r'DATA "([^"\n]*)"?',
                    lambda m: 'DATA ' + ','.join(f'{ord(c) | 128:03o}' for c in m[1]), source)
    lines = []
    for line in source.splitlines():
        code, separator, comment = line.partition(';')
        for label in ('LT', 'EQ', 'GT', 'LE', 'GE', 'NE'):
            code = re.sub(r'\b' + label + r'\b', 'CMP' + label, code)
        code = code.replace('save:', 'SAVE:').replace('load:', 'LOAD:')
        if 'If found SCR command then load memory pointer' in comment:
            code = 'SCRATCH:   LHI HIGH OLDPG26        '
        lines.append(code + separator + comment)
    source = '\n'.join(lines)
    start = source.index('INPORT:')
    end = source.index(';;; Page one', start)
    source = source[:start] + CONSOLE + source[end:]
    # Use SCR's existing initialization on cold start, without changing code
    # addresses after page zero. SAVE and LOAD retain the original no-op behavior.
    entry = '\tORG 000#100'
    assert source.count(entry) == 1
    source = source.replace(entry, '\tORG 000#100\n        JMP SCRATCH           ; cold start: initialize BASIC before READY', 1)
    note = '''; Generated by scelbal/prepare.py from the archived 2012 fast version.
; ntv8008 changes: character console, cold-start SCR initialization, A08
; HIGH/LOW and reservation syntax, explicit mark-parity text bytes, reserved
; comparison-label renaming, SAVE/LOAD label case, and END directive.
; Original copyright/permission notice above is retained without alteration.
; See ../scelbal/README.md for provenance, terms, usage, and limitations.

'''
    position = source.index('ENDPGRAM:')
    return source[:position] + note + source[position:] + '\n\n        END\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check generated source without writing')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    text = adapt()
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            parser.exit(1, f'{args.output}: regenerate with scelbal/prepare.py\n')
    else:
        args.output.write_bytes(text.encode('ascii'))


if __name__ == '__main__':
    main()
