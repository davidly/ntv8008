; HELLO FOR THE ORIGINAL INTEL MAC8 8008 MACRO CROSS-ASSEMBLER.
; MAC8 USES THE LATER 8080-STYLE 8008 MNEMONICS: MVI H,N FOR LHI N.
; COMMENTS ARE UPPERCASE BECAUSE MAC8 LISTS LOWERCASE AS SPACES.
CONOUT  EQU 10                 ; NTV8008 CONSOLE OUTPUT PORT
LOADHL  MACRO ADR              ; POINT H AND L AT ADR
        MVI H,ADR SHR 8
        MVI L,ADR AND 0FFH
        ENDM
        ORG 64                 ; NTV8008'S DEFAULT ENTRY POINT
        LOADHL MSG
        CALL PRINT
        HLT
PRINT:  MOV A,M                ; PRINT THE ZERO-TERMINATED STRING AT HL
        ANA A
        RZ
        OUT CONOUT
        INR L
        JNZ PRINT
        INR H                  ; THE STRING MAY CROSS A PAGE
        JMP PRINT
MSG:    DB 'HELLO FROM MAC8!',10,0
        END
