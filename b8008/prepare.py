#!/usr/bin/env python3
"""Expand small assembly macros; BASIC tokenization/execution stays on the 8008."""
import argparse
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def addresses(source):
    """Resolve only the simple fixed EQU addresses used by workspace macros."""
    values={}
    for line in source.splitlines():
        words=line.split(';',1)[0].split()
        if len(words)==3 and words[1]=='EQU':
            value=immediate(words[2],values)
            if isinstance(value,int):
                values[words[0]]=value
    return values


def immediate(text, values):
    match=re.fullmatch(r'(HIGH|LOW) (.+)',text)
    if match:
        value=immediate(match[2],values)
        if isinstance(value,int):
            return value>>8 if match[1]=='HIGH' else value&255
    elif text in values:
        return values[text]
    elif re.fullmatch(r'[0-9A-F]+H',text):
        return int(text[:-1],16)
    elif re.fullmatch(r'[0-9]+D',text):
        return int(text[:-1])
    else:
        match=re.fullmatch(r'(\w+)\+([0-9]+)D',text)
        if match and match[1] in values:
            return values[match[1]]+int(match[2])
    return text


def address_loads(lines, values):
    # Straight-line register facts only: every label, call, or branch ends a
    # region. LHI/LLI leave flags untouched, so redundant reloads can disappear.
    known={'H':None,'L':None}
    result=[]
    returns={'RET','RFC','RFZ','RFS','RFP','RTC','RTZ','RTS','RTP'}
    for line in lines:
        code=line.split(';',1)[0].strip()
        if not code:
            result.append(line)
            continue
        if ':' in code or not line[0].isspace():
            known={'H':None,'L':None}
        words=code.split(None,1)
        op=words[0]
        if op in ('LHI','LLI'):
            register=op[1]
            value=immediate(words[1],values)
            if known[register]==value:
                continue
            known[register]=value
        elif op in ('INH','DCH','INL','DCL'):
            register=op[-1]
            value=known[register]
            known[register]=(value+(1 if op.startswith('IN') else -1))&255 if isinstance(value,int) else None
        elif re.fullmatch(r'L[HL][ABCDEHLM]',op):
            if op[1]!=op[2]:
                known[op[1]]=None
        elif op.startswith('J') or op in returns or op in ('CAL','RST','ORG','DATA','HLT'):
            known={'H':None,'L':None}
        result.append(line)
    return result

def adapt():
    lines = ['; Generated by b8008/prepare.py from b8008/basic.src.',
             '; BSD-3-Clause; original project implementation, 2026.']
    serial = 0
    source=(ROOT/'b8008/basic.src').read_text()
    for raw in source.splitlines():
        code = raw.split(';', 1)[0].strip().split()
        if not code or code[0] not in ('LD','ST','LDW','STW','CALL','RETURN'):
            lines.append(raw)
            continue
        op = code[0]
        name = code[1] if len(code)>1 else ''
        lines.append('; '+raw.strip())
        def address(symbol):
            return ['        LHI HIGH '+symbol, '        LLI LOW '+symbol]
        if op in ('LD','ST'):
            lines += address(name) + ['        '+('LAM' if op=='LD' else 'LMA')]
        elif op in ('LDW','STW'):
            lines += address(name) + (['        LEM','        INL','        LDM'] if op=='LDW' else ['        LME','        INL','        LMD'])
        elif op=='CALL':
            serial += 1
            ret = 'XR'+str(serial)
            # Push the known return address directly, preserving live BC/DE.
            lines += address('STKP') + ['        LAM', '        CPI 252D',
                '        JFC STACKERR', '        LLA', '        LHI HIGH CSTACK',
                '        LMI LOW '+ret, '        INL', '        LMI HIGH '+ret,
                '        INL', '        LAL'] + address('STKP') + [
                '        LMA', '        JMP '+name, ret+':']
        else:
            lines += ['        JMP SRET']
    return '\n'.join(address_loads(lines,addresses(source)))+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=ROOT/'a08/b8008.asm'
    source=adapt()
    if args.check:
        if not path.exists() or path.read_text()!=source:
            parser.error('a08/b8008.asm needs regeneration')
    else:
        path.write_bytes(source.encode('ascii'))

if __name__=='__main__':
    main()
