#!/usr/bin/env python3
"""Expand small assembly macros; BASIC tokenization/execution stays on the 8008."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def adapt():
    lines = ['; Generated by b8008/prepare.py from b8008/basic.src.',
             '; BSD-3-Clause; original project implementation, 2026.']
    serial = 0
    for raw in (ROOT/'b8008/basic.src').read_text().splitlines():
        code = raw.split(';', 1)[0].strip().split()
        if not code or code[0] not in ('LD','ST','LDW','STW','CALL','RETURN'):
            lines.append(raw)
            continue
        op = code[0]
        name = code[1] if len(code)>1 else ''
        lines.append('; '+raw.strip())
        def address(symbol):
            return ['        LHI HIGH '+symbol, '        LLI LOW '+symbol]
        if op in ('LD','ST'):
            lines += address(name) + ['        '+('LAM' if op=='LD' else 'LMA')]
        elif op in ('LDW','STW'):
            lines += address(name) + (['        LEM','        INL','        LDM'] if op=='LDW' else ['        LME','        INL','        LMD'])
        elif op=='CALL':
            serial += 1
            ret = 'XR'+str(serial)
            # Push the known return address directly, preserving live BC/DE.
            lines += address('STKP') + ['        LAM', '        CPI 252D',
                '        JFC STACKERR', '        LLA', '        LHI HIGH CSTACK',
                '        LMI LOW '+ret, '        INL', '        LMI HIGH '+ret,
                '        INL', '        LAL'] + address('STKP') + [
                '        LMA', '        JMP '+name, ret+':']
        else:
            lines += ['        JMP SRET']
    return '\n'.join(lines)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=ROOT/'a08/b8008.asm'
    source=adapt()
    if args.check:
        if not path.exists() or path.read_text()!=source:
            parser.error('a08/b8008.asm needs regeneration')
    else:
        path.write_bytes(source.encode('ascii'))

if __name__=='__main__':
    main()
