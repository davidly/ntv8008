#!/usr/bin/env python3
"""Adapt Paul Robson's 8008 Tiny BASIC to A08 and ntv8008, offline."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'robson/upstream/basic.asm'
OUTPUT = ROOT / 'a08/robson.asm'
SOURCE_SHA256 = '20b53d4ad4ea67011939cb6047ae091bddb6e1f5a3c33e5687cbc0da8120f4f2'


def adapt():
    if hashlib.sha256(UPSTREAM.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('Pinned upstream basic.asm checksum mismatch')
    source = UPSTREAM.read_text(encoding='ascii')
    # The tail is the author's development-only program autoloader, not BASIC.
    source = source[:source.index('\t\torg \t400h')]
    source = re.sub(r'^\s*call\s+400h[^\n]*', '', source, flags=re.M)
    start = source.index('PrintCharacter:')
    end = source.index('InputLine:', start)
    source = source[:start] + '''PrintCharacter:
        mov a,b
        out 10
        ret
        org 18h
''' + source[end:]
    start = source.index('InputLine:')
    end = source.index('\t\torg \t038h', start)
    line_reader = source[start:end]
    line_reader = line_reader.replace('InputLine:', 'HostLine:')
    line_reader = re.sub(r'\bin\s+0\b', 'call HostInput', line_reader)
    source = source[:start] + 'InputLine:\n        jmp HostLine\n\n' + source[end:]
    # Preserve RST addresses, expose a normal default entry at 0x40, and move
    # the evaluator and subsequent code out of the restart-vector area.
    source = source.replace('Evaluate:', '''        jmp Evaluate
        org 40h
        jmp COMMAND_New
        org 100h
Evaluate:''', 1)
    # The host's input port blocks. A background poll would eat future session
    # input (or end on EOF) before the BASIC program had finished executing.
    start = source.index('__CR_Loop:')
    pos = source.index('\n', start)
    tail = source[pos:]
    tail, count = re.subn(r'\bin\s+0\b[^\n]*',
                          'xra a ; no background keyboard poll on this console',
                          tail, count=1)
    assert count == 1
    source = source[:pos] + tail
    source = re.sub(r'\bin\s+0\b', 'call HostInput', source)
    source += '\n        org 800h\n' + line_reader
    source += '''
HostInput:
        in 2
        ani 7fh
        cpi 127
        rnz
        mvi a,8
        ret
        end
'''

    regs = {'a':'A', 'b':'B', 'c':'C', 'd':'D', 'e':'E', 'h':'H', 'l':'L', 'm':'M'}
    alu = {'add':'AD', 'adc':'AC', 'sub':'SU', 'sbb':'SB',
           'ana':'ND', 'ora':'OR', 'xra':'XR', 'cmp':'CP'}
    simple = {'call':'CAL', 'jmp':'JMP', 'ret':'RET', 'jz':'JTZ', 'jnz':'JFZ',
              'jc':'JTC', 'jnc':'JFC', 'jm':'JTS', 'jp':'JFS',
              'rz':'RTZ', 'rnz':'RFZ', 'rc':'RTC', 'rm':'RTS',
              'ani':'NDI', 'ori':'ORI', 'xri':'XRI', 'in':'INP',
              'out':'OUT', 'adi':'ADI', 'aci':'ACI', 'sui':'SUI', 'cpi':'CPI',
              'ral':'RAL', 'rar':'RAR', 'org':'ORG', 'end':'END'}
    output = ['; Generated by robson/prepare.py; edit the adapter, not this file.',
              '; Upstream: Paul Robson, MIT license; see robson/upstream/LICENSE.',
              '; Native console on input 2/output octal 12; default entry 0x40.',
              '; No language extensions. Program autoload and run polling omitted.']
    for line in source.splitlines():
        quoted = False
        cut = len(line)
        for i, char in enumerate(line):
            if char == "'":
                quoted = not quoted
            elif char == ';' and not quoted:
                cut = i
                break
        code, comment = line[:cut], line[cut + 1:]
        if not code.strip():
            if comment:
                output.append(';' + comment)
            continue
        if re.match(r'\s*cpu\b', code, re.I):
            continue
        equate = re.match(r'^\s*(\w+)\s*=\s*(.*?)\s*$', code)
        if equate:
            output.append(f'{equate[1]} EQU {equate[2]}'.upper())
            continue
        match = re.match(r'^\s*(?:(\w+):\s*)?(\w+)?\s*(.*?)\s*$', code)
        if not match:
            raise ValueError(line)
        label, op, arg = match.groups()
        prefix = label.upper() + ':' if label else ''
        if not op:
            output.append(prefix)
            continue
        op = op.lower()
        if op == 'mov':
            a,b = map(str.strip, arg.lower().split(','))
            translated, arg = 'L' + regs[a] + regs[b], ''
        elif op == 'mvi':
            reg,arg = map(str.strip, arg.split(',', 1))
            translated = 'L' + regs[reg.lower()] + 'I'
        elif op in alu:
            translated, arg = alu[op] + regs[arg.lower()], ''
        elif op in ('inr', 'dcr'):
            translated, arg = ('IN' if op == 'inr' else 'DC') + regs[arg.lower()], ''
        elif op == 'rst':
            translated = 'RST'
            if arg.lower() == 'evaluate':
                arg = '38H'  # restart stub, not the relocated evaluator body
        elif op in simple:
            translated = simple[op]
        else:
            raise ValueError(f'Unknown upstream instruction: {line}')
        # A08 is octal by default; AS source integers are decimal unless suffixed.
        parts = re.split(r"('[^']*')", arg)
        for i in range(0, len(parts), 2):
            parts[i] = re.sub(r'\b(\d+)\b(?![hH\w])', r'\1D', parts[i])
            parts[i] = parts[i].upper()
        arg = ''.join(parts)
        output.append(f'{prefix:16s}{translated} {arg}'.rstrip() +
                      (' ;' + comment if comment else ''))
    return '\n'.join(output) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = adapt()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit('a08/robson.asm is stale; run robson/prepare.py')
    else:
        OUTPUT.write_bytes(generated.encode('ascii'))


if __name__ == '__main__':
    main()
